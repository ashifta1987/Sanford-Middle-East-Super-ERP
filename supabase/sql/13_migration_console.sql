-- ============ Functions the UI calls ============
-- Start a run: returns run_id. The UI then uploads to sap-exports/<storage_prefix> and calls migration_submit.
CREATE OR REPLACE FUNCTION erp.migration_request(p_company varchar, p_kind text, p_notes text DEFAULT NULL)
RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = erp, pg_temp AS $$
DECLARE v_run uuid := gen_random_uuid(); v_busy uuid;
BEGIN
  IF NOT erp.migration_is_admin() THEN RAISE EXCEPTION 'only admin or IT positions can start a migration' USING ERRCODE = '42501'; END IF;
  IF NOT erp.can_see(p_company) THEN RAISE EXCEPTION 'company % is not in your company list', p_company USING ERRCODE = '42501'; END IF;
  IF NOT EXISTS (SELECT 1 FROM sap._company WHERE company_code = p_company) THEN RAISE EXCEPTION 'unknown company %', p_company; END IF;
  IF p_kind NOT IN ('full', 'tables', 'structure_only') THEN RAISE EXCEPTION 'kind must be full, tables or structure_only'; END IF;
  SELECT run_id INTO v_busy FROM erp.migration_run
   WHERE company_code = p_company AND status IN ('uploading', 'queued', 'validating', 'loading', 'rebuilding', 'checking') LIMIT 1;
  IF FOUND THEN RAISE EXCEPTION 'company % already has a run in progress (%)', p_company, v_busy; END IF;
  INSERT INTO erp.migration_run (run_id, company_code, kind, status, created_by, storage_prefix, notes)
  VALUES (v_run, p_company, p_kind, 'uploading', erp.current_user_id(), p_company || '/' || v_run || '/', p_notes);
  INSERT INTO erp.audit_log (actor, company_code, action, object, object_ref, detail)
  VALUES (coalesce(erp.current_user_id()::text, current_user), p_company, 'migration_request', 'migration_run', v_run::text,
          jsonb_build_object('kind', p_kind, 'notes', p_notes));
  RETURN v_run;
END $$;

-- Upload finished: hand the run to the worker.
CREATE OR REPLACE FUNCTION erp.migration_submit(p_run uuid) RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = erp, pg_temp AS $$
DECLARE r erp.migration_run;
BEGIN
  SELECT * INTO r FROM erp.migration_run WHERE run_id = p_run FOR UPDATE;
  IF NOT FOUND OR NOT erp.migration_can_read(r.company_code) THEN RAISE EXCEPTION 'run not found' USING ERRCODE = '42501'; END IF;
  IF r.status <> 'uploading' THEN RAISE EXCEPTION 'run is %, only an uploading run can be submitted', r.status; END IF;
  UPDATE erp.migration_run SET status = 'queued' WHERE run_id = p_run;
  INSERT INTO erp.audit_log (actor, company_code, action, object, object_ref) VALUES (erp.current_user_id()::text, r.company_code, 'migration_submit', 'migration_run', p_run::text);
  RETURN 'queued';
END $$;

-- Cancel / "Stop run". Uploading or queued: cancelled at once ('cancelled'). Validating, loading, rebuilding or
-- checking: a stop is requested ('stop_requested'); the worker stops before its next step, rolls the company back
-- to exactly what it was before the run, and marks the run cancelled with an info issue.
-- FOR NO KEY UPDATE, not FOR UPDATE: the worker's open transaction holds KEY SHARE locks on this row.
CREATE OR REPLACE FUNCTION erp.migration_cancel(p_run uuid) RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = erp, pg_temp AS $$
DECLARE r erp.migration_run;
BEGIN
  SELECT * INTO r FROM erp.migration_run WHERE run_id = p_run FOR NO KEY UPDATE;
  IF NOT FOUND OR NOT erp.migration_can_read(r.company_code) THEN RAISE EXCEPTION 'run not found' USING ERRCODE = '42501'; END IF;
  IF r.status IN ('uploading', 'queued') THEN
    UPDATE erp.migration_run SET status = 'cancelled', finished_at = now() WHERE run_id = p_run;
    INSERT INTO erp.audit_log (actor, company_code, action, object, object_ref) VALUES (erp.current_user_id()::text, r.company_code, 'migration_cancel', 'migration_run', p_run::text);
    RETURN 'cancelled';
  ELSIF r.status IN ('validating', 'loading', 'rebuilding', 'checking') THEN
    IF r.stop_requested_at IS NULL THEN
      UPDATE erp.migration_run SET stop_requested_at = now(), stop_requested_by = erp.current_user_id() WHERE run_id = p_run;
      INSERT INTO erp.audit_log (actor, company_code, action, object, object_ref) VALUES (erp.current_user_id()::text, r.company_code, 'migration_stop', 'migration_run', p_run::text);
    END IF;
    RETURN 'stop_requested';
  END IF;
  RAISE EXCEPTION 'run is %, only an uploading, queued or running run can be cancelled', r.status;
END $$;

-- Change an issue's status (open / accepted / fixed). Admin or IT. Accepting a critical issue needs a note.
CREATE OR REPLACE FUNCTION erp.migration_resolve_issue(p_issue bigint, p_status text, p_note text DEFAULT NULL)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = erp, pg_temp AS $$
DECLARE i erp.migration_issue; r erp.migration_run;
BEGIN
  SELECT * INTO i FROM erp.migration_issue WHERE issue_id = p_issue FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'issue not found' USING ERRCODE = '42501'; END IF;
  SELECT * INTO r FROM erp.migration_run WHERE run_id = i.run_id;
  IF NOT erp.migration_can_read(r.company_code) OR (i.company_code IS NOT NULL AND NOT erp.can_see(i.company_code)) THEN
    RAISE EXCEPTION 'only admin or IT positions can change migration issues' USING ERRCODE = '42501';
  END IF;
  IF p_status NOT IN ('open', 'accepted', 'fixed') THEN RAISE EXCEPTION 'status must be open, accepted or fixed'; END IF;
  IF r.status = 'signed_off' THEN RAISE EXCEPTION 'run is signed off - issues can no longer change'; END IF;
  IF p_status = 'accepted' AND i.severity = 'critical' AND coalesce(trim(p_note), '') = '' THEN
    RAISE EXCEPTION 'accepting a critical issue needs a note saying why';
  END IF;
  UPDATE erp.migration_issue
     SET status = p_status, note = coalesce(p_note, note),
         resolved_by = CASE WHEN p_status = 'open' THEN NULL ELSE erp.current_user_id() END,
         resolved_at = CASE WHEN p_status = 'open' THEN NULL ELSE now() END
   WHERE issue_id = p_issue;
  INSERT INTO erp.audit_log (actor, company_code, action, object, object_ref, detail)
  VALUES (erp.current_user_id()::text, r.company_code, 'migration_resolve_issue', 'migration_issue', p_issue::text,
          jsonb_build_object('from', i.status, 'to', p_status, 'note', p_note, 'severity', i.severity));
  RETURN p_status;
END $$;

-- Sign off one role (finance / it / business). The caller's position must carry a module allowed for that role
-- (erp.migration_role_module). Refused unless the run is needs_review and no critical issue is open.
-- When finance, IT and business have all approved, the run becomes signed_off.
CREATE OR REPLACE FUNCTION erp.migration_sign(p_run uuid, p_role text, p_decision text, p_comment text DEFAULT NULL)
RETURNS text LANGUAGE plpgsql SECURITY DEFINER SET search_path = erp, pg_temp AS $$
DECLARE r erp.migration_run; v_crit bigint; v_status text;
BEGIN
  IF p_role NOT IN ('finance', 'it', 'business') THEN RAISE EXCEPTION 'role must be finance, it or business'; END IF;
  IF p_decision NOT IN ('approved', 'rejected') THEN RAISE EXCEPTION 'decision must be approved or rejected'; END IF;
  IF erp.current_user_id() IS NULL THEN RAISE EXCEPTION 'sign-off needs a signed-in user' USING ERRCODE = '42501'; END IF;
  SELECT * INTO r FROM erp.migration_run WHERE run_id = p_run FOR UPDATE;
  IF NOT FOUND OR NOT erp.can_see(r.company_code) THEN RAISE EXCEPTION 'run not found' USING ERRCODE = '42501'; END IF;
  IF NOT erp.migration_can_sign(p_role) THEN
    RAISE EXCEPTION 'your position cannot sign off as %', p_role USING ERRCODE = '42501';
  END IF;
  IF r.status <> 'needs_review' THEN RAISE EXCEPTION 'run is %, sign-off is only possible while it needs review', r.status; END IF;
  SELECT count(*) INTO v_crit FROM erp.migration_issue WHERE run_id = p_run AND severity = 'critical' AND status = 'open';
  IF p_decision = 'approved' AND v_crit > 0 THEN
    RAISE EXCEPTION 'sign-off refused: % critical issue(s) still open', v_crit USING ERRCODE = 'P0001';
  END IF;
  INSERT INTO erp.migration_signoff (run_id, role, signed_by, decision, comment) VALUES (p_run, p_role, erp.current_user_id(), p_decision, p_comment)
  ON CONFLICT (run_id, role) DO UPDATE SET signed_by = EXCLUDED.signed_by, signed_at = now(), decision = EXCLUDED.decision, comment = EXCLUDED.comment;
  v_status := r.status;
  IF (SELECT count(*) FROM erp.migration_signoff WHERE run_id = p_run AND decision = 'approved') = 3 THEN
    UPDATE erp.migration_run SET status = 'signed_off', finished_at = now() WHERE run_id = p_run;
    v_status := 'signed_off';
  END IF;
  INSERT INTO erp.audit_log (actor, company_code, action, object, object_ref, detail)
  VALUES (erp.current_user_id()::text, r.company_code, 'migration_sign', 'migration_run', p_run::text,
          jsonb_build_object('role', p_role, 'decision', p_decision, 'comment', p_comment));
  RETURN v_status;
END $$;

-- Progress for the UI: one row per step (run columns repeated). Admin/IT, or a sign-off user of that company.
DROP FUNCTION IF EXISTS erp.migration_status(uuid);
CREATE FUNCTION erp.migration_status(p_run uuid)
RETURNS TABLE (run_id uuid, company_code varchar, kind text, run_status text, created_at timestamptz, started_at timestamptz,
               finished_at timestamptz, step_no smallint, step_code text, step_status text, step_rows bigint,
               step_started_at timestamptz, step_finished_at timestamptz, step_seconds numeric, step_message text,
               files bigint, data_files bigint, tables_loaded bigint, checks bigint, checks_failed bigint,
               critical_open bigint, warning_open bigint, info_open bigint, signoffs jsonb,
               stop_requested_at timestamptz, stop_requested_by uuid, report_figures bigint, report_missing bigint)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = erp, pg_temp AS $$
DECLARE r erp.migration_run;
BEGIN
  SELECT * INTO r FROM erp.migration_run m WHERE m.run_id = p_run;
  IF NOT FOUND OR NOT (erp.migration_can_read(r.company_code) OR (erp.can_see(r.company_code) AND erp.migration_can_sign(NULL))) THEN
    RAISE EXCEPTION 'run not found' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
  SELECT r.run_id, r.company_code, r.kind, r.status, r.created_at, r.started_at, r.finished_at,
         s.step_no, s.code, s.status, s.rows, s.started_at, s.finished_at,
         round(extract(epoch FROM coalesce(s.finished_at, CASE WHEN s.status = 'running' THEN clock_timestamp() END) - s.started_at)::numeric, 1),
         s.message,
         (SELECT count(*) FROM erp.migration_file f WHERE f.run_id = p_run),
         (SELECT count(*) FROM erp.migration_file f WHERE f.run_id = p_run AND f.kind = 'data_csv'),
         (SELECT count(*) FROM sap._load_log l WHERE l.run_id = p_run AND l.status IN ('loaded', 'count_mismatch', 'column_mismatch')),
         (SELECT count(*) FROM erp.migration_check c WHERE c.run_id = p_run),
         (SELECT count(*) FROM erp.migration_check c WHERE c.run_id = p_run AND NOT c.ok),
         (SELECT count(*) FROM erp.migration_issue i WHERE i.run_id = p_run AND i.status = 'open' AND i.severity = 'critical'),
         (SELECT count(*) FROM erp.migration_issue i WHERE i.run_id = p_run AND i.status = 'open' AND i.severity = 'warning'),
         (SELECT count(*) FROM erp.migration_issue i WHERE i.run_id = p_run AND i.status = 'open' AND i.severity = 'info'),
         (SELECT coalesce(jsonb_agg(jsonb_build_object('role', o.role, 'decision', o.decision, 'signed_by', o.signed_by,
                                                       'signed_at', o.signed_at, 'comment', o.comment) ORDER BY o.role), '[]'::jsonb)
            FROM erp.migration_signoff o WHERE o.run_id = p_run),
         r.stop_requested_at, r.stop_requested_by,
         (SELECT count(*) FROM erp.migration_report_figure f WHERE f.run_id = p_run),
         (SELECT count(*) FROM erp.migration_issue i WHERE i.run_id = p_run AND i.status = 'open' AND i.issue_key LIKE 'report_missing:%')
    FROM (SELECT 1) one LEFT JOIN erp.migration_step s ON s.run_id = p_run
   ORDER BY s.step_no;
END $$;

-- What a reviewer reads before signing: checks (failed first) and issues of a run that needs review or is signed off.
-- Admin/IT always; finance / IT / business sign-off users of that company once the run needs review.
DROP FUNCTION IF EXISTS erp.migration_review(uuid, text);
CREATE FUNCTION erp.migration_review(p_run uuid, p_area text DEFAULT NULL)
RETURNS TABLE (item text, id bigint, company_code varchar, area text, name text, severity text, status text,
               sap_value numeric, raw_value numeric, app_value numeric, difference numeric, ok boolean, detail jsonb,
               report_value numeric, report_source text, report_ok boolean, report_required boolean)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = erp, pg_temp AS $$
DECLARE r erp.migration_run;
BEGIN
  SELECT * INTO r FROM erp.migration_run m WHERE m.run_id = p_run;
  IF NOT FOUND OR NOT (erp.migration_can_read(r.company_code)
                       OR (erp.can_see(r.company_code) AND erp.migration_can_sign(NULL) AND r.status IN ('needs_review', 'signed_off'))) THEN
    RAISE EXCEPTION 'run not found' USING ERRCODE = '42501';
  END IF;
  RETURN QUERY
  SELECT 'issue'::text, i.issue_id, i.company_code, i.area, i.title, i.severity, i.status, NULL::numeric, NULL::numeric, NULL::numeric,
         NULL::numeric, i.status <> 'open', jsonb_build_object('detail', i.detail, 'table', i.table_name, 'note', i.note, 'resolved_at', i.resolved_at),
         NULL::numeric, NULL::text, NULL::boolean, NULL::boolean
    FROM erp.migration_issue i
   WHERE i.run_id = p_run AND (p_area IS NULL OR i.area = p_area) AND (i.company_code IS NULL OR erp.can_see(i.company_code))
  UNION ALL
  SELECT 'check', c.check_id, c.company_code, c.area, c.check_name, NULL, NULL, c.sap_value, c.raw_value, c.app_value, c.difference, c.ok, c.detail,
         c.report_value, c.report_source,
         CASE WHEN c.report_value IS NOT NULL THEN abs(c.report_value - coalesce(c.raw_value, 0)) <= 0.01 AND abs(c.report_value - coalesce(c.app_value, 0)) <= 0.01 END,
         c.company_code = r.company_code AND c.check_name = ANY (erp.migration_report_headline())
    FROM erp.migration_check c
   WHERE c.run_id = p_run AND (p_area IS NULL OR c.area = p_area) AND (c.company_code IS NULL OR erp.can_see(c.company_code))
   ORDER BY 1 DESC, 12, 4, 3, 5;
END $$;

-- The checks Finance must back with a figure printed from SAP (a missing one is a warning on the run's company).
CREATE OR REPLACE FUNCTION erp.migration_report_headline() RETURNS text[] LANGUAGE sql IMMUTABLE AS $$
  SELECT ARRAY['open A/R (invoices + down payments - credit notes)', 'open A/P (invoices + down payments - credit notes)',
               'account group assets', 'account group liabilities', 'account group equity', 'account group revenue',
               'account group expenses', 'on hand value, all warehouses']
$$;

-- Compares the report figures of a run with its checks: fills migration_check.report_value, opens a critical issue
-- when the figure differs from the raw or the app value by more than 0.01, closes it when it matches, and keeps a
-- warning open for every headline check of the run's company without a figure.
CREATE OR REPLACE FUNCTION erp.migration_compare_report(p_run uuid, p_company varchar DEFAULT NULL)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = erp, pg_temp AS $$
DECLARE r record; k text; v_run_co varchar; n bigint := 0;
BEGIN
  SELECT company_code INTO v_run_co FROM erp.migration_run WHERE run_id = p_run;
  UPDATE erp.migration_check c SET report_value = f.value, report_source = f.source
    FROM erp.migration_report_figure f
   WHERE c.run_id = p_run AND f.run_id = p_run AND f.company_code = c.company_code AND f.area = c.area AND f.check_name = c.check_name
     AND (p_company IS NULL OR c.company_code = p_company)
     AND (c.report_value, c.report_source) IS DISTINCT FROM (f.value, f.source);
  UPDATE erp.migration_check c SET report_value = NULL, report_source = NULL
   WHERE c.run_id = p_run AND c.report_value IS NOT NULL AND (p_company IS NULL OR c.company_code = p_company)
     AND NOT EXISTS (SELECT 1 FROM erp.migration_report_figure f WHERE f.run_id = p_run AND f.company_code = c.company_code AND f.area = c.area AND f.check_name = c.check_name);
  FOR r IN SELECT c.company_code, c.area, c.check_name, c.raw_value, c.app_value, c.report_value, c.report_source,
                  c.company_code = v_run_co AND c.check_name = ANY (erp.migration_report_headline()) AS headline
             FROM erp.migration_check c WHERE c.run_id = p_run AND (p_company IS NULL OR c.company_code = p_company)
              AND (c.report_value IS NOT NULL OR (c.company_code = v_run_co AND c.check_name = ANY (erp.migration_report_headline()))) LOOP
    k := 'report:' || r.company_code || ':' || r.area || ':' || r.check_name;
    IF r.report_value IS NULL THEN
      PERFORM erp.migration_add_issue(p_run, r.company_code, 'warning', r.area, 'report_missing:' || r.company_code || ':' || r.check_name,
              format('Finance has not entered the SAP report figure: %s', r.check_name),
              format('%s: SAP copy %s, app %s. Enter the figure printed from SAP with erp.migration_set_report_figure.', r.company_code, r.raw_value, r.app_value));
      CONTINUE;
    END IF;
    n := n + 1;
    UPDATE erp.migration_issue SET status = 'fixed', resolved_at = now(), note = 'report figure entered'
     WHERE run_id = p_run AND issue_key = 'report_missing:' || r.company_code || ':' || r.check_name AND status = 'open';
    IF abs(r.report_value - coalesce(r.raw_value, 0)) > 0.01 OR abs(r.report_value - coalesce(r.app_value, 0)) > 0.01 THEN
      PERFORM erp.migration_add_issue(p_run, r.company_code, 'critical', r.area, k,
              format('%s: SAP report figure differs - %s', r.company_code, r.check_name),
              format('SAP report %s (%s), SAP copy %s, app %s', r.report_value, coalesce(r.report_source, 'no source given'), r.raw_value, r.app_value));
    ELSE
      UPDATE erp.migration_issue SET status = 'fixed', resolved_at = now(), note = 'SAP report figure matches'
       WHERE run_id = p_run AND issue_key = k AND status = 'open';
    END IF;
  END LOOP;
  -- figures entered for checks that no longer exist / headline checks that no longer need one
  UPDATE erp.migration_issue i SET status = 'fixed', resolved_at = now(), note = 'check no longer present'
   WHERE i.run_id = p_run AND i.status = 'open' AND (i.issue_key LIKE 'report:%' OR i.issue_key LIKE 'report_missing:%')
     AND (p_company IS NULL OR i.company_code = p_company)
     AND NOT EXISTS (SELECT 1 FROM erp.migration_check c WHERE c.run_id = p_run AND c.company_code = i.company_code
                      AND i.issue_key IN ('report:' || c.company_code || ':' || c.area || ':' || c.check_name, 'report_missing:' || c.company_code || ':' || c.check_name));
  RETURN n;
END $$;

-- Finance (or admin/IT) enters the figure printed from SAP for one check (area + check_name as in migration_check).
-- p_value NULL removes it. Only while the run needs review. Returns the check's comparison right away.
CREATE OR REPLACE FUNCTION erp.migration_set_report_figure(p_run uuid, p_company varchar, p_area text, p_check_name text,
                                                           p_value numeric, p_source text DEFAULT NULL)
RETURNS TABLE (check_name text, report_value numeric, raw_value numeric, app_value numeric, report_ok boolean)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = erp, pg_temp AS $$
DECLARE r erp.migration_run;
BEGIN
  SELECT * INTO r FROM erp.migration_run m WHERE m.run_id = p_run;
  IF NOT FOUND OR NOT erp.can_see(r.company_code) OR NOT erp.can_see(p_company)
     OR NOT (erp.migration_can_read(r.company_code) OR erp.migration_can_sign('finance')) THEN
    RAISE EXCEPTION 'only finance sign-off users or admin/IT can enter SAP report figures' USING ERRCODE = '42501';
  END IF;
  IF r.status <> 'needs_review' THEN RAISE EXCEPTION 'run is %, report figures can be entered only while it needs review', r.status; END IF;
  IF NOT EXISTS (SELECT 1 FROM erp.migration_check c WHERE c.run_id = p_run AND c.company_code = p_company AND c.area = p_area AND c.check_name = p_check_name) THEN
    RAISE EXCEPTION 'run has no check "%" in area % for %', p_check_name, p_area, p_company;
  END IF;
  IF p_value IS NULL THEN
    DELETE FROM erp.migration_report_figure f WHERE f.run_id = p_run AND f.company_code = p_company AND f.area = p_area AND f.check_name = p_check_name;
  ELSE
    INSERT INTO erp.migration_report_figure AS f (run_id, company_code, area, check_name, value, source, entered_by)
    VALUES (p_run, p_company, p_area, p_check_name, p_value, p_source, erp.current_user_id())
    ON CONFLICT ON CONSTRAINT migration_report_figure_pkey DO UPDATE SET value = EXCLUDED.value, source = EXCLUDED.source,
       entered_by = EXCLUDED.entered_by, entered_at = now();
  END IF;
  PERFORM erp.migration_compare_report(p_run, p_company);
  INSERT INTO erp.audit_log (actor, company_code, action, object, object_ref, detail)
  VALUES (erp.current_user_id()::text, p_company, 'migration_set_report_figure', 'migration_run', p_run::text,
          jsonb_build_object('area', p_area, 'check', p_check_name, 'value', p_value, 'source', p_source));
  RETURN QUERY SELECT c.check_name, c.report_value, c.raw_value, c.app_value,
         CASE WHEN c.report_value IS NOT NULL THEN abs(c.report_value - coalesce(c.raw_value, 0)) <= 0.01 AND abs(c.report_value - coalesce(c.app_value, 0)) <= 0.01 END
    FROM erp.migration_check c WHERE c.run_id = p_run AND c.company_code = p_company AND c.area = p_area AND c.check_name = p_check_name;
END $$;

-- ============ Worker-only functions (service role) ============
-- The whole app sync for one company as ONE transaction (erp.sync_company commits after every step, so a failure
-- there leaves the app layer half-updated). Runs the same steps, in the same order, read from erp.sync_company.
CREATE OR REPLACE FUNCTION erp.migration_sync_company(p_company varchar)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = erp, pg_temp AS $$
DECLARE f text; n bigint; total bigint := 0; t timestamptz; src text;
BEGIN
  SELECT prosrc INTO src FROM pg_proc WHERE oid = 'erp.sync_company(varchar)'::regprocedure;
  PERFORM set_config('erp.sync', 'on', true);
  INSERT INTO erp.company (company_code, legal_name, short_name, country, currency, licence_type, sap_schema)
  SELECT c.company_code, c.legal_name, c.legal_name, c.country, c.currency, c.licence_type, c.sap_schema FROM sap._company c WHERE c.company_code = p_company
  ON CONFLICT (company_code) DO UPDATE SET legal_name = EXCLUDED.legal_name, country = EXCLUDED.country, currency = EXCLUDED.currency,
       licence_type = EXCLUDED.licence_type, sap_schema = EXCLUDED.sap_schema;
  FOR f IN SELECT x.m[1] FROM regexp_matches(src, 'erp\.(sync_[a-z0-9_]+)\(p_company\)', 'g') WITH ORDINALITY AS x(m, i) ORDER BY x.i LOOP
    t := clock_timestamp();
    EXECUTE format('SELECT erp.%I($1)', f) INTO n USING p_company;
    INSERT INTO erp.sync_log (company_code, step, rows_written, started_at) VALUES (p_company, f, n, t);
    total := total + coalesce(n, 0);
  END LOOP;
  PERFORM set_config('erp.sync', 'off', true);
  RETURN total;
END $$;

-- Orphan links for one company: same test as 03_orphan_check.sql, over the links in sap._link.
CREATE OR REPLACE FUNCTION erp.migration_orphans(p_company varchar)
RETURNS TABLE (link text, child_table text, child_column text, parent_table text, parent_column text, rows bigint, sample text[])
LANGUAGE plpgsql SECURITY DEFINER SET search_path = erp, pg_temp AS $$
DECLARE l record; n bigint; s text[];
BEGIN
  IF NOT EXISTS (SELECT 1 FROM sap._link) THEN RAISE EXCEPTION 'sap._link is empty - run 03_orphan_check.sql once'; END IF;
  FOR l IN SELECT k.* FROM sap._link k
            WHERE to_regclass(format('sap.%I', k.child_table)) IS NOT NULL AND to_regclass(format('sap.%I', k.parent_table)) IS NOT NULL
            ORDER BY k.child_table, k.constraint_name LOOP
    EXECUTE format('SELECT count(*) FROM sap.%I c WHERE c.company_code = $1 AND c.%I IS NOT NULL AND NOT EXISTS '
                   '(SELECT 1 FROM sap.%I p WHERE p.company_code = c.company_code AND p.%I = c.%I)',
                   l.child_table, l.child_column, l.parent_table, l.parent_column, l.child_column) INTO n USING p_company;
    IF n > 0 THEN
      EXECUTE format('SELECT array_agg(v) FROM (SELECT DISTINCT c.%I::text v FROM sap.%I c WHERE c.company_code = $1 AND c.%I IS NOT NULL AND NOT EXISTS '
                     '(SELECT 1 FROM sap.%I p WHERE p.company_code = c.company_code AND p.%I = c.%I) ORDER BY 1 LIMIT 5) x',
                     l.child_column, l.child_table, l.child_column, l.parent_table, l.parent_column, l.child_column) INTO s USING p_company;
      link := format('%s.%s -> %s.%s', l.child_table, l.child_column, l.parent_table, l.parent_column);
      child_table := l.child_table; child_column := l.child_column; parent_table := l.parent_table; parent_column := l.parent_column;
      rows := n; sample := s;
      RETURN NEXT;
    END IF;
  END LOOP;
END $$;

-- Adds or refreshes one issue (keeps a human decision: an accepted issue stays accepted).
CREATE OR REPLACE FUNCTION erp.migration_add_issue(p_run uuid, p_company varchar, p_severity text, p_area text, p_key text,
                                                   p_title text, p_detail text DEFAULT NULL, p_table text DEFAULT NULL)
RETURNS bigint LANGUAGE sql SECURITY DEFINER SET search_path = erp, pg_temp AS $$
  INSERT INTO erp.migration_issue AS i (run_id, company_code, severity, area, title, detail, table_name, issue_key)
  VALUES (p_run, p_company, p_severity, p_area, p_title, p_detail, p_table, p_key)
  ON CONFLICT (run_id, issue_key) DO UPDATE
     SET severity = EXCLUDED.severity, title = EXCLUDED.title, detail = EXCLUDED.detail, table_name = EXCLUDED.table_name,
         status = CASE WHEN i.status = 'fixed' THEN 'open' ELSE i.status END,
         resolved_at = CASE WHEN i.status = 'fixed' THEN NULL ELSE i.resolved_at END
  RETURNING issue_id
$$;

-- Cross-checks one company (p_company) or every company (NULL) for a run, filling migration_check and migration_issue:
--   row_counts  per table: row_counts.csv (sap) vs loaded (log) vs rows now in the raw table; this run's load, else the latest
--   orphans     links whose value has no parent in the same company (erp.migration_orphans)
--   app_tables  erp.check_sync and erp.check_deleted
--   finance     journals balance (all lines and per journal), trial balance per account raw JDT1 vs app journal_line,
--               open A/R and A/P from documents, customer and supplier balances from journal BP lines
--   stock       on-hand quantity and value (OnHand x AvgPrice) per warehouse, raw OITW vs app stock_balance
--   hr          employees and active employees, raw OHEM vs app employee
-- Returns the run's totals after the check.
CREATE OR REPLACE FUNCTION erp.migration_cross_check(p_company varchar, p_run uuid)
RETURNS TABLE (companies integer, checks bigint, failed bigint, critical_open bigint, warning_open bigint, info_open bigint)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = erp, pg_temp AS $$
DECLARE
  co varchar; v_cos varchar[]; v_found text[] := '{}'; k text; r record; n bigint; v_a numeric; v_b numeric; v_skipped text[];
  areas constant text[] := ARRAY['row_counts', 'orphans', 'app_tables', 'finance', 'stock', 'hr'];
BEGIN
  IF NOT EXISTS (SELECT 1 FROM erp.migration_run m WHERE m.run_id = p_run) THEN RAISE EXCEPTION 'run % not found', p_run; END IF;
  SELECT array_agg(c.company_code ORDER BY c.company_code) INTO v_cos FROM sap._company c
   WHERE (p_company IS NULL AND c.in_scope) OR c.company_code = p_company;
  IF v_cos IS NULL THEN RAISE EXCEPTION 'unknown company %', p_company; END IF;
  DELETE FROM erp.migration_check c WHERE c.run_id = p_run AND c.company_code = ANY (v_cos) AND c.area = ANY (areas);

  FOREACH co IN ARRAY v_cos LOOP
    -- (a) row counts --------------------------------------------------------------------------------
    v_skipped := '{}';
    FOR r IN SELECT DISTINCT ON (l.table_name) l.*, to_regclass(format('sap.%I', l.table_name)) IS NOT NULL AS in_schema
               FROM sap._load_log l WHERE l.company_code = co
              ORDER BY l.table_name, (l.run_id = p_run) DESC, l.load_id DESC LOOP
      IF NOT r.in_schema THEN v_skipped := v_skipped || r.table_name; CONTINUE; END IF;
      EXECUTE format('SELECT count(*) FROM sap.%I WHERE company_code = $1', r.table_name) INTO n USING co;
      INSERT INTO erp.migration_check (run_id, company_code, area, check_name, sap_value, raw_value, app_value, difference, ok, detail)
      VALUES (p_run, co, 'row_counts', r.table_name, r.rows_expected, n, NULL, n - coalesce(r.rows_expected, n),
              r.status <> 'failed' AND (r.rows_expected IS NULL OR r.rows_expected = n) AND (r.rows_loaded IS NULL OR r.rows_loaded = n),
              jsonb_build_object('status', r.status, 'rows_loaded', r.rows_loaded, 'message', r.message, 'load_run', r.run_id, 'loaded_at', r.loaded_at));
      IF r.status = 'failed' THEN
        k := 'load_failed:' || co || ':' || r.table_name; v_found := v_found || k;
        PERFORM erp.migration_add_issue(p_run, co, 'critical', 'row_counts', k, format('%s: %s did not load', co, r.table_name), r.message, r.table_name);
      ELSIF (r.rows_expected IS NOT NULL AND r.rows_expected <> n) OR (r.rows_loaded IS NOT NULL AND r.rows_loaded <> n) THEN
        k := 'rows:' || co || ':' || r.table_name; v_found := v_found || k;
        PERFORM erp.migration_add_issue(p_run, co, 'critical', 'row_counts', k,
                format('%s: %s has %s rows, SAP export says %s', co, r.table_name, n, coalesce(r.rows_expected::text, '?')),
                format('rows expected %s, loaded %s, in the raw table now %s. %s', r.rows_expected, r.rows_loaded, n, coalesce(r.message, '')), r.table_name);
      END IF;
      IF r.status = 'column_mismatch' THEN
        k := 'columns:' || co || ':' || r.table_name; v_found := v_found || k;
        PERFORM erp.migration_add_issue(p_run, co, 'warning', 'row_counts', k, format('%s: %s columns differ from the export', co, r.table_name), r.message, r.table_name);
      END IF;
    END LOOP;
    IF cardinality(v_skipped) > 0 THEN
      INSERT INTO erp.migration_check (run_id, company_code, area, check_name, sap_value, raw_value, ok, detail)
      VALUES (p_run, co, 'row_counts', 'tables skipped (not in the sap schema)', cardinality(v_skipped), 0, true, jsonb_build_object('tables', to_jsonb(v_skipped)));
      k := 'skipped:' || co; v_found := v_found || k;
      PERFORM erp.migration_add_issue(p_run, co, 'info', 'row_counts', k, format('%s: %s exported tables are not in the sap schema and were skipped', co, cardinality(v_skipped)),
              'SAP working/report tables, views or the unused HR add-on set: ' || array_to_string(v_skipped[1:30], ', ') || CASE WHEN cardinality(v_skipped) > 30 THEN ' ...' ELSE '' END);
    END IF;

    -- (b) orphans -----------------------------------------------------------------------------------
    n := 0;
    FOR r IN SELECT * FROM erp.migration_orphans(co) LOOP
      n := n + r.rows;
      INSERT INTO erp.migration_check (run_id, company_code, area, check_name, sap_value, raw_value, difference, ok, detail)
      VALUES (p_run, co, 'orphans', r.link, 0, r.rows, r.rows, false, jsonb_build_object('sample', to_jsonb(r.sample)));
      k := 'orphan:' || co || ':' || r.link; v_found := v_found || k;
      PERFORM erp.migration_add_issue(p_run, co, 'critical', 'orphans', k, format('%s: %s rows of %s point at a missing %s', co, r.rows, r.child_table, r.parent_table),
              format('%s. Values: %s', r.link, array_to_string(r.sample, ', ')), r.child_table);
    END LOOP;
    INSERT INTO erp.migration_check (run_id, company_code, area, check_name, sap_value, raw_value, difference, ok, detail)
    VALUES (p_run, co, 'orphans', 'orphan rows over all links', 0, n, n, n = 0, jsonb_build_object('links', (SELECT count(*) FROM sap._link)));

    -- (c) app tables --------------------------------------------------------------------------------
    FOR r IN SELECT * FROM erp.check_sync(co) LOOP
      INSERT INTO erp.migration_check (run_id, company_code, area, check_name, raw_value, app_value, difference, ok)
      VALUES (p_run, co, 'app_tables', r.check_name, r.sap_value, r.erp_value, r.erp_value - r.sap_value, r.ok);
      IF NOT r.ok THEN
        k := 'sync:' || co || ':' || r.check_name; v_found := v_found || k;
        PERFORM erp.migration_add_issue(p_run, co, 'critical', 'app_tables', k, format('%s: app layer differs from SAP - %s', co, r.check_name),
                format('raw sap %s, app %s', r.sap_value, r.erp_value));
      END IF;
    END LOOP;
    n := 0;
    FOR r IN SELECT * FROM erp.check_deleted(co) LOOP
      n := n + r.rows;
      INSERT INTO erp.migration_check (run_id, company_code, area, check_name, raw_value, app_value, difference, ok)
      VALUES (p_run, co, 'app_tables', 'gone from SAP: ' || r.what, 0, r.rows, r.rows, false);
      k := 'deleted:' || co || ':' || r.what; v_found := v_found || k;
      PERFORM erp.migration_add_issue(p_run, co, 'warning', 'app_tables', k, format('%s: %s %s rows in the app are no longer in SAP', co, r.rows, r.what),
              'The sync only adds and updates. Review these rows (erp.check_deleted) before removing them.');
    END LOOP;
    INSERT INTO erp.migration_check (run_id, company_code, area, check_name, raw_value, app_value, difference, ok)
    VALUES (p_run, co, 'app_tables', 'app rows gone from SAP (check_deleted)', 0, n, n, n = 0);

    -- (d) finance -----------------------------------------------------------------------------------
    SELECT coalesce(sum("Debit"), 0) - coalesce(sum("Credit"), 0) INTO v_a FROM sap."JDT1" WHERE company_code = co;
    SELECT coalesce(sum(l.debit - l.credit), 0) INTO v_b FROM erp.journal_line l JOIN erp.journal_entry e USING (company_code, trans_id)
     WHERE l.company_code = co AND e.source = 'sap';
    INSERT INTO erp.migration_check (run_id, company_code, area, check_name, sap_value, raw_value, app_value, difference, ok)
    VALUES (p_run, co, 'finance', 'journal lines: debit minus credit', 0, v_a, v_b, v_b - v_a, round(v_a, 2) = 0 AND round(v_b, 2) = 0);
    IF round(v_a, 2) <> 0 OR round(v_b, 2) <> 0 THEN
      k := 'jbal:' || co; v_found := v_found || k;
      PERFORM erp.migration_add_issue(p_run, co, 'critical', 'finance', k, format('%s: journal debits and credits do not balance', co), format('raw %s, app %s', v_a, v_b));
    END IF;
    SELECT count(*), (array_agg("TransId"::text ORDER BY "TransId"))[1:10] INTO n, v_skipped
      FROM (SELECT "TransId" FROM sap."JDT1" WHERE company_code = co GROUP BY 1 HAVING round(sum(coalesce("Debit", 0) - coalesce("Credit", 0)), 2) <> 0) x;
    SELECT count(*) INTO v_b FROM (SELECT l.trans_id FROM erp.journal_line l JOIN erp.journal_entry e USING (company_code, trans_id)
      WHERE l.company_code = co AND e.source = 'sap' GROUP BY 1 HAVING round(sum(l.debit - l.credit), 2) <> 0) x;
    INSERT INTO erp.migration_check (run_id, company_code, area, check_name, sap_value, raw_value, app_value, difference, ok, detail)
    VALUES (p_run, co, 'finance', 'journals that do not balance', 0, n, v_b, v_b - n, n = 0 AND v_b = 0, jsonb_build_object('raw_trans_ids', to_jsonb(v_skipped)));
    IF n > 0 OR v_b > 0 THEN
      k := 'junbal:' || co; v_found := v_found || k;
      PERFORM erp.migration_add_issue(p_run, co, 'critical', 'finance', k, format('%s: %s journal(s) do not balance', co, greatest(n, v_b)),
              'raw TransId: ' || coalesce(array_to_string(v_skipped, ', '), '-'));
    END IF;
    -- trial balance per account
    n := 0;
    FOR r IN WITH raw AS (SELECT "Account" AS acct, sum(coalesce("Debit", 0)) d, sum(coalesce("Credit", 0)) c FROM sap."JDT1" WHERE company_code = co GROUP BY 1),
                  app AS (SELECT l.acct_code AS acct, sum(l.debit) d, sum(l.credit) c FROM erp.journal_line l JOIN erp.journal_entry e USING (company_code, trans_id)
                           WHERE l.company_code = co AND e.source = 'sap' GROUP BY 1)
             SELECT coalesce(raw.acct, app.acct) acct, raw.d - raw.c AS rb, app.d - app.c AS ab, raw.d rd, raw.c rc, app.d ad, app.c ac,
                    (SELECT a."AcctName" FROM sap."OACT" a WHERE a.company_code = co AND a."AcctCode" = coalesce(raw.acct, app.acct)) AS acct_name
               FROM raw FULL JOIN app ON app.acct = raw.acct ORDER BY 1 LOOP
      INSERT INTO erp.migration_check (run_id, company_code, area, check_name, raw_value, app_value, difference, ok, detail)
      VALUES (p_run, co, 'finance', 'trial balance ' || r.acct, r.rb, r.ab, coalesce(r.ab, 0) - coalesce(r.rb, 0),
              r.rd IS NOT NULL AND r.ad IS NOT NULL AND round(r.rd, 2) = round(r.ad, 2) AND round(r.rc, 2) = round(r.ac, 2),
              jsonb_build_object('account', r.acct, 'name', r.acct_name, 'raw_debit', r.rd, 'raw_credit', r.rc, 'app_debit', r.ad, 'app_credit', r.ac));
      IF NOT (r.rd IS NOT NULL AND r.ad IS NOT NULL AND round(r.rd, 2) = round(r.ad, 2) AND round(r.rc, 2) = round(r.ac, 2)) THEN
        n := n + 1;
        k := 'tb:' || co || ':' || r.acct; v_found := v_found || k;
        PERFORM erp.migration_add_issue(p_run, co, 'critical', 'finance', k, format('%s: trial balance of account %s differs', co, r.acct),
                format('%s: raw debit %s credit %s, app debit %s credit %s', coalesce(r.acct_name, r.acct), r.rd, r.rc, r.ad, r.ac));
      END IF;
    END LOOP;
    INSERT INTO erp.migration_check (run_id, company_code, area, check_name, raw_value, app_value, difference, ok)
    SELECT p_run, co, 'finance', 'trial balance: accounts that differ',
           (SELECT count(DISTINCT "Account") FROM sap."JDT1" WHERE company_code = co),
           (SELECT count(DISTINCT acct_code) FROM erp.journal_line WHERE company_code = co), n, n = 0;
    -- trial balance by account group (SAP OACT.GroupMask: 1 assets, 2 liabilities, 3 equity, 4 revenue, 5-8 expenses
    -- (cost of sales, operating, non-operating, tax), 9 / none other). Balance = debit - credit, all journal lines.
    FOR r IN WITH g(name, masks) AS (VALUES ('assets', ARRAY[1]), ('liabilities', ARRAY[2]), ('equity', ARRAY[3]), ('revenue', ARRAY[4]),
                                            ('expenses', ARRAY[5, 6, 7, 8]), ('other / no group', ARRAY[9, -1])),
                  raw AS (SELECT coalesce(a."GroupMask", -1) gm, sum(coalesce(j."Debit", 0) - coalesce(j."Credit", 0)) b, count(DISTINCT j."Account") na
                            FROM sap."JDT1" j LEFT JOIN sap."OACT" a ON a.company_code = j.company_code AND a."AcctCode" = j."Account"
                           WHERE j.company_code = co GROUP BY 1),
                  app AS (SELECT coalesce(a.group_mask, -1) gm, sum(l.debit - l.credit) b FROM erp.journal_line l
                            JOIN erp.journal_entry e USING (company_code, trans_id)
                            LEFT JOIN erp.account a ON a.company_code = l.company_code AND a.acct_code = l.acct_code
                           WHERE l.company_code = co AND e.source = 'sap' GROUP BY 1)
             SELECT g.name, coalesce((SELECT sum(raw.b) FROM raw WHERE raw.gm = ANY (g.masks)), 0) rb,
                    coalesce((SELECT sum(app.b) FROM app WHERE app.gm = ANY (g.masks)), 0) ab,
                    coalesce((SELECT sum(raw.na) FROM raw WHERE raw.gm = ANY (g.masks)), 0) na, g.masks
               FROM g LOOP
      CONTINUE WHEN r.name = 'other / no group' AND r.rb = 0 AND r.ab = 0;
      INSERT INTO erp.migration_check (run_id, company_code, area, check_name, raw_value, app_value, difference, ok, detail)
      VALUES (p_run, co, 'finance', 'account group ' || r.name, r.rb, r.ab, r.ab - r.rb, round(r.rb, 2) = round(r.ab, 2),
              jsonb_build_object('group_mask', to_jsonb(r.masks), 'accounts', r.na, 'sign', 'debit - credit'));
      IF round(r.rb, 2) <> round(r.ab, 2) THEN
        k := 'group:' || co || ':' || r.name; v_found := v_found || k;
        PERFORM erp.migration_add_issue(p_run, co, 'critical', 'finance', k, format('%s: account group %s differs', co, r.name), format('raw %s, app %s', r.rb, r.ab));
      END IF;
      IF r.name = 'other / no group' THEN
        k := 'group_other:' || co; v_found := v_found || k;
        PERFORM erp.migration_add_issue(p_run, co, 'warning', 'finance', k, format('%s: journal lines on accounts without an account group', co),
                format('balance %s on accounts with GroupMask 9 or none - check OACT', r.rb));
      END IF;
    END LOOP;
    -- open A/R and A/P from documents (open = not cancelled, not closed; credit notes count negative)
    FOR r IN SELECT x.name, x.objs, x.raw_sql FROM (VALUES
               ('open A/R (invoices + down payments - credit notes)', ARRAY[13, 203, 14],
                'SELECT coalesce(sum(t), 0) FROM (SELECT "DocTotal" - coalesce("PaidToDate", 0) t, "CANCELED" cx, "DocStatus" st FROM sap."OINV" WHERE company_code = $1 '
                'UNION ALL SELECT "DocTotal" - coalesce("PaidToDate", 0), "CANCELED", "DocStatus" FROM sap."ODPI" WHERE company_code = $1 '
                'UNION ALL SELECT -("DocTotal" - coalesce("PaidToDate", 0)), "CANCELED", "DocStatus" FROM sap."ORIN" WHERE company_code = $1) d '
                'WHERE coalesce(cx, ''N'') NOT IN (''Y'', ''C'') AND coalesce(st, ''O'') <> ''C'''),
               ('open A/P (invoices + down payments - credit notes)', ARRAY[18, 204, 19],
                'SELECT coalesce(sum(t), 0) FROM (SELECT "DocTotal" - coalesce("PaidToDate", 0) t, "CANCELED" cx, "DocStatus" st FROM sap."OPCH" WHERE company_code = $1 '
                'UNION ALL SELECT "DocTotal" - coalesce("PaidToDate", 0), "CANCELED", "DocStatus" FROM sap."ODPO" WHERE company_code = $1 '
                'UNION ALL SELECT -("DocTotal" - coalesce("PaidToDate", 0)), "CANCELED", "DocStatus" FROM sap."ORPC" WHERE company_code = $1) d '
                'WHERE coalesce(cx, ''N'') NOT IN (''Y'', ''C'') AND coalesce(st, ''O'') <> ''C''')) x(name, objs, raw_sql) LOOP
      EXECUTE r.raw_sql INTO v_a USING co;
      SELECT coalesce(sum(d.sign * (coalesce(d.total, 0) - coalesce(d.paid, 0))), 0) INTO v_b FROM erp.document d
       WHERE d.company_code = co AND d.obj_type = ANY (r.objs) AND d.status = 'open' AND d.source = 'sap';
      INSERT INTO erp.migration_check (run_id, company_code, area, check_name, raw_value, app_value, difference, ok)
      VALUES (p_run, co, 'finance', r.name, v_a, v_b, v_b - v_a, round(v_a, 2) = round(v_b, 2));
      IF round(v_a, 2) <> round(v_b, 2) THEN
        k := 'open:' || co || ':' || r.name; v_found := v_found || k;
        PERFORM erp.migration_add_issue(p_run, co, 'critical', 'finance', k, format('%s: %s differs', co, r.name), format('raw %s, app %s', v_a, v_b));
      END IF;
    END LOOP;
    -- customer / supplier balances from the journal lines posted to business partners
    FOR r IN SELECT * FROM (VALUES ('customer balance (journal BP lines)', 'C', 'customer', 1), ('supplier balance (journal BP lines)', 'S', 'supplier', -1)) x(name, sap_kind, app_kind, sgn) LOOP
      SELECT r.sgn * coalesce(sum(coalesce(j."Debit", 0) - coalesce(j."Credit", 0)), 0) INTO v_a FROM sap."JDT1" j
        JOIN sap."OCRD" b ON b.company_code = j.company_code AND b."CardCode" = j."ShortName"
       WHERE j.company_code = co AND j."ShortName" IS DISTINCT FROM j."Account" AND coalesce(b."CardType", 'C') = r.sap_kind;
      SELECT r.sgn * coalesce(sum(l.debit - l.credit), 0) INTO v_b FROM erp.journal_line l
        JOIN erp.journal_entry e USING (company_code, trans_id)
        JOIN erp.business_partner b ON b.company_code = l.company_code AND b.card_code = l.short_name
       WHERE l.company_code = co AND e.source = 'sap' AND b.kind = r.app_kind;
      INSERT INTO erp.migration_check (run_id, company_code, area, check_name, raw_value, app_value, difference, ok)
      VALUES (p_run, co, 'finance', r.name, v_a, v_b, v_b - v_a, round(v_a, 2) = round(v_b, 2));
      IF round(v_a, 2) <> round(v_b, 2) THEN
        k := 'bpbal:' || co || ':' || r.name; v_found := v_found || k;
        PERFORM erp.migration_add_issue(p_run, co, 'critical', 'finance', k, format('%s: %s differs', co, r.name), format('raw %s, app %s', v_a, v_b));
      END IF;
    END LOOP;

    -- (e) stock per warehouse -------------------------------------------------------------------------
    FOR r IN WITH raw AS (SELECT "WhsCode" w, sum(coalesce("OnHand", 0)) q, sum(coalesce("OnHand", 0) * coalesce("AvgPrice", 0)) v
                            FROM sap."OITW" WHERE company_code = co GROUP BY 1),
                  app AS (SELECT whs_code w, sum(on_hand) q, sum(on_hand * coalesce(avg_cost, 0)) v FROM erp.stock_balance WHERE company_code = co GROUP BY 1)
             SELECT coalesce(raw.w, app.w) w, raw.q rq, app.q aq, raw.v rv, app.v av FROM raw FULL JOIN app ON app.w = raw.w ORDER BY 1 LOOP
      INSERT INTO erp.migration_check (run_id, company_code, area, check_name, raw_value, app_value, difference, ok, detail)
      VALUES (p_run, co, 'stock', 'on hand qty ' || r.w, r.rq, r.aq, coalesce(r.aq, 0) - coalesce(r.rq, 0), round(coalesce(r.rq, -1), 3) = round(coalesce(r.aq, -2), 3), jsonb_build_object('warehouse', r.w)),
             (p_run, co, 'stock', 'on hand value ' || r.w, r.rv, r.av, coalesce(r.av, 0) - coalesce(r.rv, 0), round(coalesce(r.rv, -1), 2) = round(coalesce(r.av, -2), 2), jsonb_build_object('warehouse', r.w));
      IF NOT (round(coalesce(r.rq, -1), 3) = round(coalesce(r.aq, -2), 3) AND round(coalesce(r.rv, -1), 2) = round(coalesce(r.av, -2), 2)) THEN
        k := 'stock:' || co || ':' || r.w; v_found := v_found || k;
        PERFORM erp.migration_add_issue(p_run, co, 'critical', 'stock', k, format('%s: stock in warehouse %s differs', co, r.w),
                format('qty raw %s app %s; value raw %s app %s', r.rq, r.aq, r.rv, r.av));
      END IF;
    END LOOP;
    SELECT coalesce(sum("OnHand"), 0) INTO v_a FROM sap."OITW" WHERE company_code = co;
    SELECT coalesce(sum(on_hand), 0) INTO v_b FROM erp.stock_balance WHERE company_code = co;
    INSERT INTO erp.migration_check (run_id, company_code, area, check_name, raw_value, app_value, difference, ok)
    VALUES (p_run, co, 'stock', 'on hand qty, all warehouses', v_a, v_b, v_b - v_a, round(v_a, 3) = round(v_b, 3));
    SELECT coalesce(sum(coalesce("OnHand", 0) * coalesce("AvgPrice", 0)), 0) INTO v_a FROM sap."OITW" WHERE company_code = co;
    SELECT coalesce(sum(on_hand * coalesce(avg_cost, 0)), 0) INTO v_b FROM erp.stock_balance WHERE company_code = co;
    INSERT INTO erp.migration_check (run_id, company_code, area, check_name, raw_value, app_value, difference, ok)
    VALUES (p_run, co, 'stock', 'on hand value, all warehouses', v_a, v_b, v_b - v_a, round(v_a, 2) = round(v_b, 2));

    -- (f) HR ----------------------------------------------------------------------------------------
    SELECT count(*) INTO v_a FROM sap."OHEM" WHERE company_code = co;
    SELECT count(*) INTO v_b FROM erp.employee WHERE company_code = co AND source = 'sap';
    INSERT INTO erp.migration_check (run_id, company_code, area, check_name, raw_value, app_value, difference, ok)
    VALUES (p_run, co, 'hr', 'employees', v_a, v_b, v_b - v_a, v_a = v_b);
    IF v_a <> v_b THEN
      k := 'hr:' || co || ':employees'; v_found := v_found || k;
      PERFORM erp.migration_add_issue(p_run, co, 'critical', 'hr', k, format('%s: employee count differs', co), format('raw OHEM %s, app %s', v_a, v_b));
    END IF;
    SELECT count(*) INTO v_a FROM sap."OHEM" WHERE company_code = co AND coalesce("Active", 'Y') = 'Y';
    SELECT count(*) INTO v_b FROM erp.employee WHERE company_code = co AND source = 'sap' AND active;
    INSERT INTO erp.migration_check (run_id, company_code, area, check_name, raw_value, app_value, difference, ok)
    VALUES (p_run, co, 'hr', 'active employees', v_a, v_b, v_b - v_a, v_a = v_b);
    IF v_a <> v_b THEN
      k := 'hr:' || co || ':active'; v_found := v_found || k;
      PERFORM erp.migration_add_issue(p_run, co, 'critical', 'hr', k, format('%s: active employee count differs', co), format('raw OHEM %s, app %s', v_a, v_b));
    END IF;
  END LOOP;

  -- issues raised by an earlier cross-check of this run that are no longer found
  UPDATE erp.migration_issue i SET status = 'fixed', resolved_at = now(), note = 'not found by the cross-check of ' || to_char(now(), 'YYYY-MM-DD HH24:MI')
   WHERE i.run_id = p_run AND i.company_code = ANY (v_cos) AND i.area = ANY (areas) AND i.status = 'open' AND NOT (i.issue_key = ANY (v_found))
     AND i.issue_key NOT LIKE 'report%';
  -- SAP report figures entered by Finance (kept across re-runs) against the fresh raw and app values
  PERFORM erp.migration_compare_report(p_run, CASE WHEN cardinality(v_cos) = 1 THEN v_cos[1] END);

  RETURN QUERY SELECT cardinality(v_cos),
    (SELECT count(*) FROM erp.migration_check c WHERE c.run_id = p_run),
    (SELECT count(*) FROM erp.migration_check c WHERE c.run_id = p_run AND NOT c.ok),
    (SELECT count(*) FROM erp.migration_issue i WHERE i.run_id = p_run AND i.status = 'open' AND i.severity = 'critical'),
    (SELECT count(*) FROM erp.migration_issue i WHERE i.run_id = p_run AND i.status = 'open' AND i.severity = 'warning'),
    (SELECT count(*) FROM erp.migration_issue i WHERE i.run_id = p_run AND i.status = 'open' AND i.severity = 'info');
END $$;

