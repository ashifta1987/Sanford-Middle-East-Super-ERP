-- Sanford ERP - Migration console (admin UI: upload one company's SAP HANA export, rebuild it, cross-check).
-- Run after 12_erp_security.sql. Safe to run again (idempotent).
--
-- Flow: the UI calls erp.migration_request(company, kind, notes) -> run_id and uploads the files to Supabase
-- Storage bucket "sap-exports" under storage_prefix (<company>/<run_id>/), then erp.migration_submit(run_id).
-- migration_worker.py picks up the queued run, rebuilds that company only (validate, stage, cast, 02, 03, 04,
-- keys, security, app sync, check_sync, check_deleted, cross_check) and writes every step, check and issue here.
-- The run ends in needs_review; finance, IT and business sign off with erp.migration_sign(); a sign-off is
-- refused while any critical issue is open (resolve or accept it with erp.migration_resolve_issue()).
--
-- Access: the tables are readable only by admin/IT positions (module 'admin' or 'it' in erp.position.module_access)
-- for companies in their erp.user_company list. App users never write them directly: requests, sign-offs and
-- issue decisions go through the SECURITY DEFINER functions below. The worker writes with the service role
-- (direct database connection). Anonymous users have no access.

CREATE SCHEMA IF NOT EXISTS erp;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN CREATE ROLE authenticated NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN CREATE ROLE anon NOLOGIN; END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN CREATE ROLE service_role NOLOGIN BYPASSRLS; END IF;
END $$;

-- ============ Tables ============
CREATE TABLE IF NOT EXISTS erp.migration_run (
    run_id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    company_code   varchar(8) NOT NULL REFERENCES sap._company,
    kind           text NOT NULL CHECK (kind IN ('full', 'tables', 'structure_only')),
    status         text NOT NULL DEFAULT 'uploading' CHECK (status IN ('queued', 'uploading', 'validating', 'loading', 'rebuilding',
                       'checking', 'needs_review', 'signed_off', 'failed', 'cancelled')),
    created_by     uuid,                            -- erp.app_user.user_id (NULL when started by the worker CLI)
    created_at     timestamptz NOT NULL DEFAULT now(),
    started_at     timestamptz,
    finished_at    timestamptz,
    storage_prefix text,                            -- folder in Storage bucket sap-exports: <company>/<run_id>/
    notes          text,
    worker         text                             -- host/pid of the worker that ran it
);
ALTER TABLE erp.migration_run ADD COLUMN IF NOT EXISTS stop_requested_at timestamptz;   -- "Stop run" pressed while running
ALTER TABLE erp.migration_run ADD COLUMN IF NOT EXISTS stop_requested_by uuid;
CREATE INDEX IF NOT EXISTS migration_run_status_idx ON erp.migration_run (status, created_at);
CREATE INDEX IF NOT EXISTS migration_run_company_idx ON erp.migration_run (company_code, created_at DESC);

CREATE TABLE IF NOT EXISTS erp.migration_file (
    file_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         uuid NOT NULL REFERENCES erp.migration_run ON DELETE CASCADE,
    path           text NOT NULL,                   -- relative to the upload root
    kind           text NOT NULL CHECK (kind IN ('data_csv', 'create_sql', 'columns_csv', 'constraints_csv', 'row_counts_csv',
                       'structure_xlsx', 'structure_csv', 'other')),
    bytes          bigint,
    table_name     text,
    status         text NOT NULL DEFAULT 'ok' CHECK (status IN ('ok', 'ignored', 'skipped', 'error')),
    message        text,
    UNIQUE (run_id, path)
);

CREATE TABLE IF NOT EXISTS erp.migration_step (
    run_id         uuid NOT NULL REFERENCES erp.migration_run ON DELETE CASCADE,
    step_no        smallint NOT NULL,
    code           text NOT NULL,                   -- validate, stage, cast, clean_02, orphans_03, links_04, real_keys,
                                                    -- security_06, app_sync, check_sync, check_deleted, cross_check
    status         text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'running', 'ok', 'warning', 'failed', 'skipped')),
    rows           bigint,
    started_at     timestamptz,
    finished_at    timestamptz,
    message        text,
    PRIMARY KEY (run_id, step_no),
    UNIQUE (run_id, code)
);

CREATE TABLE IF NOT EXISTS erp.migration_check (
    check_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         uuid NOT NULL REFERENCES erp.migration_run ON DELETE CASCADE,
    company_code   varchar(8),                      -- the company checked (a cross-check covers every company)
    area           text NOT NULL,                   -- structure, row_counts, orphans, app_tables, finance, stock, hr
    check_name     text NOT NULL,
    sap_value      numeric,                         -- what SAP says (row_counts.csv, field list, or the expected value)
    raw_value      numeric,                         -- what the raw sap schema holds
    app_value      numeric,                         -- what the app (erp) layer holds
    difference     numeric,
    ok             boolean NOT NULL,
    detail         jsonb,
    checked_at     timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE erp.migration_check ADD COLUMN IF NOT EXISTS report_value numeric;   -- the figure Finance printed from SAP (migration_report_figure)
ALTER TABLE erp.migration_check ADD COLUMN IF NOT EXISTS report_source text;
CREATE INDEX IF NOT EXISTS migration_check_run_idx ON erp.migration_check (run_id, area, ok);

-- Figures Finance prints from SAP itself (trial balance by account or account group, open A/R, open A/P, stock value).
-- Kept apart from the checks, so a re-run of the cross-check keeps them; compared with the raw and app values.
CREATE TABLE IF NOT EXISTS erp.migration_report_figure (
    run_id         uuid NOT NULL REFERENCES erp.migration_run ON DELETE CASCADE,
    company_code   varchar(8) NOT NULL,
    area           text NOT NULL,
    check_name     text NOT NULL,
    value          numeric NOT NULL,
    source         text,                            -- e.g. 'SAP B1 Trial Balance 31.10.2026, printed by F. Finance'
    entered_by     uuid,
    entered_at     timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (run_id, company_code, area, check_name)
);

CREATE TABLE IF NOT EXISTS erp.migration_issue (
    issue_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         uuid NOT NULL REFERENCES erp.migration_run ON DELETE CASCADE,
    company_code   varchar(8),
    severity       text NOT NULL CHECK (severity IN ('critical', 'warning', 'info')),
    area           text NOT NULL,
    title          text NOT NULL,
    detail         text,
    table_name     text,
    status         text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'accepted', 'fixed')),
    resolved_by    uuid,
    resolved_at    timestamptz,
    note           text,
    issue_key      text NOT NULL,                   -- stable key, so a re-check updates instead of duplicating
    created_at     timestamptz NOT NULL DEFAULT now(),
    UNIQUE (run_id, issue_key)
);
CREATE INDEX IF NOT EXISTS migration_issue_open_idx ON erp.migration_issue (run_id, status, severity);

CREATE TABLE IF NOT EXISTS erp.migration_signoff (
    run_id         uuid NOT NULL REFERENCES erp.migration_run ON DELETE CASCADE,
    role           text NOT NULL CHECK (role IN ('finance', 'it', 'business')),
    signed_by      uuid NOT NULL,
    signed_at      timestamptz NOT NULL DEFAULT now(),
    decision       text NOT NULL CHECK (decision IN ('approved', 'rejected')),
    comment        text,
    PRIMARY KEY (run_id, role)
);

-- Which position modules may sign which role (erp.position.module_access). Edit with the service role.
CREATE TABLE IF NOT EXISTS erp.migration_role_module (
    role           text NOT NULL CHECK (role IN ('finance', 'it', 'business')),
    module         text NOT NULL,
    PRIMARY KEY (role, module)
);
INSERT INTO erp.migration_role_module VALUES ('finance', 'finance'), ('it', 'it'), ('it', 'admin'), ('business', 'business'), ('business', 'sales')
ON CONFLICT DO NOTHING;

-- Link list used by erp.migration_orphans (03_orphan_check.sql refreshes it every time it runs).
CREATE TABLE IF NOT EXISTS sap._link (child_table text NOT NULL, constraint_name text NOT NULL, child_column text NOT NULL,
    parent_table text NOT NULL, parent_column text NOT NULL, PRIMARY KEY (child_table, constraint_name));
ALTER TABLE sap._link ENABLE ROW LEVEL SECURITY;

-- ============ Who may do what ============
CREATE OR REPLACE FUNCTION erp.migration_is_admin() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = erp, pg_temp AS $$
  SELECT erp.has_module('admin') OR erp.has_module('it')
$$;
CREATE OR REPLACE FUNCTION erp.migration_can_read(p_company varchar) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = erp, pg_temp AS $$
  SELECT erp.migration_is_admin() AND erp.can_see(p_company)
$$;
CREATE OR REPLACE FUNCTION erp.migration_can_sign(p_role text) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = erp, pg_temp AS $$
  SELECT EXISTS (SELECT 1 FROM erp.migration_role_module m WHERE (p_role IS NULL OR m.role = p_role) AND erp.has_module(m.module))
$$;

